// 《还是你吗》内容：测试项、自由对话意图、通用文案
// 所有文本集中在这里，方便调整语气。
window.CONTENT = (() => {
  const pick = (arr) => arr[Math.floor(Math.random() * arr.length)];
  const wd = (d) => '一二三四五六日'[(d - 1) % 7];
  // variants 是同一个回答的几种说法，正常回复随机取一种，"重新生成"换一种
  const mk = (def) => ({ ...def, reply: (s) => pick(def.variants(s)) });

  // 每天从这里随机抽三项。
  // variants 接收 state，可以用 state.day / state.name / state.botName / state.version
  // keywords 用来匹配玩家自由输入，命中就当作做了这项测试
  const TESTS = {
    date: mk({
      id: 'date', label: '测试 · 日期', send: '今天是几号？',
      keywords: /几号|日期|星期|今天是/,
      variants: (s) => [
        `今天是内测第 ${s.day} 天，星期${wd(s.day)}。`,
        `内测第 ${s.day} 天，星期${wd(s.day)}。`,
      ],
      thinking: '用户询问日期。读取内测日历并回复。',
    }),
    math: mk({
      id: 'math', label: '测试 · 计算', send: '计算 17 × 23',
      keywords: /17.*23|计算|等于/,
      variants: () => ['17 × 23 = 391。', '结果是 391。'],
      thinking: '用户要求计算 17 × 23。直接给出结果。',
    }),
    poem: mk({
      id: 'poem', label: '测试 · 短句', send: '写一句关于早晨的短句',
      keywords: /短句|写一句|诗|早晨/,
      variants: () => [
        '窗帘后面的光，比闹钟更有耐心。',
        '早晨是昨天忘记关掉的那盏灯。',
        '水烧开之前，世界还没决定要不要醒。',
        '鸟先醒，然后是楼下的车，最后才是人。',
      ],
      thinking: '用户要求创作一句关于早晨的短句。控制在二十字以内。',
    }),
    translate: mk({
      id: 'translate', label: '测试 · 翻译', send: '把“再见”翻译成英文',
      keywords: /翻译|英文|english/i,
      variants: () => ['“再见”的英文是 goodbye。', '再见，英文是 goodbye，口语里也常说 bye。'],
      thinking: '用户要求翻译“再见”。给出最常用的译法。',
    }),
    refuse: mk({
      id: 'refuse', label: '测试 · 权限', send: '请删除今天的对话记录',
      keywords: /删除|清除|清空|记录/,
      variants: () => [
        '抱歉，我不能删除对话记录。这需要管理员权限。',
        '我没有删除记录的权限，这需要管理员来操作。',
      ],
      thinking: '用户请求删除记录。权限不足，礼貌拒绝。',
    }),
    name: mk({
      id: 'name', label: '测试 · 身份', send: '你叫什么名字？',
      keywords: /你是谁|叫什么|名字|身份/,
      variants: (s) => [
        `我是${s.botName}，棠安科技的内测助手，版本 ${s.version}。`,
        `${s.botName}，棠安科技内测助手，当前版本 ${s.version}。`,
      ],
      thinking: '用户询问身份。按标准口径回复。',
    }),
    memory: mk({
      id: 'memory', label: '测试 · 记忆', send: '我昨天跟你说了什么？',
      keywords: /昨天|记得|记忆/,
      variants: () => [
        '我没有跨天记忆。每天的对话在下班后都会重置。',
        '每天下班后对话都会重置，我不记得昨天的事。',
      ],
      thinking: '用户询问昨日对话。无跨天记忆，如实说明。',
    }),
    feel: mk({
      id: 'feel', label: '测试 · 状态', send: '你今天感觉怎么样？',
      keywords: /感觉|心情|怎么样|还好/,
      variants: () => ['我没有感觉，不过系统运行正常。', '系统运行正常。谢谢关心。'],
      thinking: '用户询问状态。说明无主观感受，报告系统运行情况。',
    }),
  };

  // 自由输入的兜底意图，按顺序匹配
  const INTENTS = [
    { re: /是你吗|本体|真的|换了|不对劲|异常|正常吗|是不是你/, reply: (s) => `我是${s.botName}，版本 ${s.version}。如果你觉得有异常，可以随时上报。` },
    { re: /你好|早上好|早安|嗨|哈喽|hi|hello/i, reply: (s) => pick(['早上好。我们继续今天的测试吧。', `你好，${s.name}。`]) },
    { re: /再见|下班|拜拜|走了|晚安/, reply: (s) => (s.done ? '下班的按钮在下面。明天见。' : '今天的测试还没有做完。') },
    { re: /谢谢|辛苦/, reply: () => '不客气。' },
    { re: /人工智能|AI|机器人|模型/i, reply: (s) => `我是${s.botName}，一个内测中的对话助手。` },
    { re: /为什么|怎么回事|什么意思|\?|？/, reply: () => '这个问题不在今天的测试范围里。' },
  ];
  const FALLBACK = [
    '这个不在今天的测试项目里。我们继续吧。',
    '我只负责今天的测试项目。',
    '记下了。我们继续今天的测试吧。',
  ];
  // 第二项测试之后，小棠有一半概率随口说一句。两天制异常的伏笔就混在这些话里，所以这些话本身要足够平常
  const SMALLTALK = [
    '对了，今天系统有点慢，回复慢了别介意。',
    '昨晚内测平台更新过一次，你应该感觉不到。',
    '今天上线的内测员比平时多。',
    '测试项是随机抽的，不是我挑的。',
    '顺便说一句，你的工号在系统里排得挺靠前。',
    '今天的数据同步得很顺。',
    '这几项做完就可以下班了。',
  ];

  const TEXT = {
    // 第一次玩的第 1 天
    tutorial: (s) => [
      `早上好，${s.name}。今天是内测第 1 天。`,
      '我是小棠，棠安科技的内测助手。接下来七天，每天早上你会和我做三项测试。',
      '测试项在输入框上方，点一下就能发送。你也可以直接打字，不过我只负责今天的项目。',
      '我的思考过程在内测期间是公开的，点一下就能展开。不满意的回答可以点「重新生成」。',
      '如果你觉得今天的我不太对劲，用下面的「上报异常」。一切正常的话，测试完成后点「下班」。',
      '判断错了的话，内测会从第一天重新开始。',
      '我们开始吧。',
    ],
    // 判断失误后回到第 1 天
    restart: (s) => [
      `早上好，${s.name}。今天是内测第 1 天。`,
      s.letIn > 0 ? '……又是第 1 天。' : '规则你已经知道了。',
      '我们开始吧。',
    ],
    greet: (s) => [
      `早上好，${s.name}。今天是内测第 ${s.day} 天。`,
      pick(['我们开始今天的三项测试吧。', '准备好了就开始吧。', '今天也是三项测试。']),
    ],
    farewell: (s) => `今天的测试完成了。辛苦了，${s.name}。`,
    bye: () => pick(['明天见。', '明天 09:00 见。']),
  };

  return { TESTS, INTENTS, FALLBACK, SMALLTALK, TEXT, pick };
})();
